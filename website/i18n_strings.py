def translate(key: str, lang: str, **kwargs) -> str:
    text = UI_STRINGS.get(lang, UI_STRINGS["sr"]).get(key) or UI_STRINGS["sr"].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text
